/// Tests rename and unlink operations on the VFS.
fn test_rename_unlink() -> Result<(), Error> {
    ::syslog::info!("vfs-test: test_rename_unlink begin");

    vfs::create_mount("/ren", 128 * 1024).map_err(|e| fat_err(e, "create_mount /ren failed"))?;

    // Create a file.
    {
        let mut file: vfs::File = vfs::OpenOptions::new()
            .write(true)
            .create(true)
            .open("/ren/orig.txt")
            .map_err(|e| fat_err(e, "failed to create orig.txt"))?;
        file.write(b"rename me")
            .map_err(|e| fat_err(e, "failed to write orig.txt"))?;
        file.flush()
            .map_err(|e| fat_err(e, "failed to flush orig.txt"))?;
    }

    // Rename the file.
    vfs::rename("/ren/orig.txt", "/ren/moved.txt").map_err(|e| fat_err(e, "rename failed"))?;

    // Verify old name is gone.
    if vfs::stat("/ren/orig.txt").is_ok() {
        return Err(Error::new(
            ErrorCode::InvalidArgument,
            "orig.txt should not exist after rename",
        ));
    }

    // Verify new name exists with correct content.
    verify_file("/ren/moved.txt", b"rename me")?;

    // Unlink the renamed file.
    vfs::unlink("/ren/moved.txt").map_err(|e| fat_err(e, "unlink failed"))?;

    // Verify the file is gone.
    if vfs::stat("/ren/moved.txt").is_ok() {
        return Err(Error::new(
            ErrorCode::InvalidArgument,
            "moved.txt should not exist after unlink",
        ));
    }

    vfs::unmount("/ren").map_err(|e| fat_err(e, "unmount /ren failed"))?;

    ::syslog::info!("vfs-test: test_rename_unlink passed");
    Ok(())
}

