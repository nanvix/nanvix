// Test: Create In-Memory Mount
//==================================================================================================

/// Tests creating an in-memory FAT filesystem via `create_mount`.
///
/// Validates write, read, stat, mkdir, readdir, rmdir, unlink, and unmount.
fn test_create_mount() -> Result<(), Error> {
    ::syslog::info!("vfs-test: test_create_mount begin");

    // Create an in-memory FAT mount.
    vfs::create_mount("/scratch", 128 * 1024).map_err(|e| fat_err(e, "create_mount failed"))?;

    // Write a file.
    {
        let mut file: vfs::File = vfs::OpenOptions::new()
            .write(true)
            .create(true)
            .open("/scratch/test.txt")
            .map_err(|e| fat_err(e, "failed to create test.txt"))?;
        file.write(b"test data")
            .map_err(|e| fat_err(e, "failed to write test.txt"))?;
        file.flush()
            .map_err(|e| fat_err(e, "failed to flush test.txt"))?;
    }

    // Read it back.
    {
        let mut file: vfs::File =
            vfs::open("/scratch/test.txt").map_err(|e| fat_err(e, "failed to open test.txt"))?;
        let content: alloc::vec::Vec<u8> = file
            .read_to_vec()
            .map_err(|e| fat_err(e, "failed to read test.txt"))?;
        if content.as_slice() != b"test data" {
            return Err(Error::new(ErrorCode::InvalidArgument, "test.txt content mismatch"));
        }
    }

    // Verify stat.
    let info: vfs::Stat =
        vfs::stat("/scratch/test.txt").map_err(|e| fat_err(e, "stat test.txt failed"))?;
    if info.is_dir() {
        return Err(Error::new(ErrorCode::InvalidArgument, "test.txt should not be a directory"));
    }
    if info.size() != 9 {
        return Err(Error::new(ErrorCode::InvalidArgument, "test.txt size mismatch"));
    }

    // Test mkdir.
    vfs::mkdir("/scratch/mydir").map_err(|e| fat_err(e, "mkdir failed"))?;

    // Verify read_dir sees both entries.
    let entries: alloc::vec::Vec<vfs::DirEntry> =
        vfs::read_dir("/scratch").map_err(|e| fat_err(e, "read_dir failed"))?;
    if entries.len() != 2 {
        return Err(Error::new(ErrorCode::InvalidArgument, "expected 2 entries in /scratch"));
    }

    // Clean up: remove directory and file, then unmount.
    vfs::rmdir("/scratch/mydir").map_err(|e| fat_err(e, "rmdir failed"))?;
    vfs::unlink("/scratch/test.txt").map_err(|e| fat_err(e, "unlink failed"))?;
    vfs::unmount("/scratch").map_err(|e| fat_err(e, "unmount failed"))?;

    ::syslog::info!("vfs-test: test_create_mount passed");
    Ok(())
}

