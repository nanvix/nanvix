/// Tests positional read/write without changing file position.
fn test_pread_pwrite() -> Result<(), Error> {
    ::syslog::info!("vfs-test: test_pread_pwrite begin");

    vfs::create_mount("/pp", 128 * 1024).map_err(|e| fat_err(e, "create_mount /pp failed"))?;

    // Create and write sequential data.
    {
        let mut file: vfs::File = vfs::OpenOptions::new()
            .write(true)
            .create(true)
            .open("/pp/data.bin")
            .map_err(|e| fat_err(e, "failed to create data.bin"))?;
        file.write(b"AABBCCDDEE")
            .map_err(|e| fat_err(e, "failed to write data.bin"))?;
        file.flush()
            .map_err(|e| fat_err(e, "failed to flush data.bin"))?;
    }

    // Open for reading and verify pread at offset.
    {
        let mut file: vfs::File =
            vfs::open("/pp/data.bin").map_err(|e| fat_err(e, "failed to open data.bin"))?;

        // Read at offset 4 (should get "CCDDEE").
        let mut buf: [u8; 6] = [0u8; 6];
        file.seek(0, 4).map_err(|e| fat_err(e, "seek failed"))?;
        let n: usize = file.read(&mut buf).map_err(|e| fat_err(e, "read failed"))?;
        if n != 6 || &buf[..6] != b"CCDDEE" {
            return Err(Error::new(ErrorCode::InvalidArgument, "pread content mismatch"));
        }

        // Verify we can still read from the start.
        file.seek(0, 0)
            .map_err(|e| fat_err(e, "seek back failed"))?;
        let mut buf2: [u8; 2] = [0u8; 2];
        let n2: usize = file
            .read(&mut buf2)
            .map_err(|e| fat_err(e, "read2 failed"))?;
        if n2 != 2 || &buf2 != b"AA" {
            return Err(Error::new(ErrorCode::InvalidArgument, "read from start mismatch"));
        }
    }

    // Clean up.
    vfs::unlink("/pp/data.bin").map_err(|e| fat_err(e, "unlink failed"))?;
    vfs::unmount("/pp").map_err(|e| fat_err(e, "unmount /pp failed"))?;

    ::syslog::info!("vfs-test: test_pread_pwrite passed");
    Ok(())
}

