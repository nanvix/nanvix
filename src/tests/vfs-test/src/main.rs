/// Encoded 8-byte "RAMFS   " tag exposed by the MicroVM RAMFS MMIO region.
const RAMFS_MMIO_TAG: u64 = u64::from_be_bytes(*b"RAMFS   ");

//==================================================================================================
// Helpers
//==================================================================================================

/// Converts a [`vfs::Fat32Error`] to an [`Error`], preserving the error code.
fn fat_err(e: vfs::Fat32Error, reason: &'static str) -> Error {
    Error::new(ErrorCode::from(e), reason)
}

//==================================================================================================
// Entry Point
//==================================================================================================

#[no_mangle]
pub fn main() -> Result<(), Error> {
    // Initialize the vfs filesystem.
    vfs::init().map_err(|e| fat_err(e, "vfs init failed"))?;

    // Run tests.
    test_create_mount()?;
    test_rename_unlink()?;
    test_chdir_cwd()?;
    test_pread_pwrite()?;
    test_ftruncate_fsync()?;
    test_ramfs_mount()?;

    Ok(())
}

//==================================================================================================
// Test: Mount RAMFS Image
//==================================================================================================

/// Tests mounting a FAT image provided via the RAMFS MMIO region.
///
/// The FAT image is generated by build.rs and passed to nanvixd via `-ramfs`.
/// Since the RAMFS region is read-only in the guest, the image is copied to a
/// heap buffer before mounting.
fn test_ramfs_mount() -> Result<(), Error> {
    ::syslog::info!("vfs-test: test_ramfs_mount begin");

    let mut cap_acquired: bool = false;
    let mut region_attached: bool = false;

    let result: Result<(), Error> = (|| {
        // Acquire IO management capability.
        pm::capctl(Capability::IoManagement, true)?;
        cap_acquired = true;

        // Attach RAMFS MMIO region.
        mm::mmio_alloc(RAMFS_MMIO_TAG)?;
        region_attached = true;

        // Get region info.
        let info: ::sys::mm::MmioRegionInfo = mm::mmio_info(RAMFS_MMIO_TAG)?;
        let total_size: usize = info.size();

        ::syslog::info!("vfs-test: ramfs region (size={})", total_size,);

        // Copy RAMFS to heap buffer (RAMFS is read-only in guest).
        let mut buffer: alloc::vec::Vec<u8> = vec![0u8; total_size];
        unsafe {
            let src: *const u8 = info.base().as_ptr();
            for (i, byte) in buffer.iter_mut().enumerate() {
                *byte = ptr::read_volatile(src.add(i));
            }
        }

        // Release MMIO region before mounting.
        mm::mmio_free(RAMFS_MMIO_TAG)?;
        region_attached = false;
        pm::capctl(Capability::IoManagement, false)?;
        cap_acquired = false;

        // Leak the buffer so it lives for the program's lifetime.
        // SAFETY: The mount holds a raw pointer into this buffer, so it
        // must not be deallocated while the mount exists.
        let leaked: &'static mut [u8] = alloc::boxed::Box::leak(buffer.into_boxed_slice());

        // Mount the FAT image.
        unsafe {
            vfs::mount_image("/ramfs", leaked.as_mut_ptr(), leaked.len())
                .map_err(|e| fat_err(e, "vfs mount failed"))?;
        }

        // Verify hello.txt exists and contains expected content.
        verify_file("/ramfs/hello.txt", b"Hello from FAT32 on Nanvix!\n")?;

        // Verify subdirectory and nested file.
        let info: vfs::Stat =
            vfs::stat("/ramfs/subdir").map_err(|e| fat_err(e, "stat subdir failed"))?;
        if !info.is_dir() {
            return Err(Error::new(ErrorCode::InvalidArgument, "subdir should be a directory"));
        }

        verify_file("/ramfs/subdir/nested.txt", b"nested content\n")?;

        // Verify read_dir on root.
        let entries: alloc::vec::Vec<vfs::DirEntry> =
            vfs::read_dir("/ramfs").map_err(|e| fat_err(e, "read_dir /ramfs failed"))?;
        if entries.len() != 2 {
            return Err(Error::new(ErrorCode::InvalidArgument, "expected 2 entries in /ramfs"));
        }

        ::syslog::info!("vfs-test: test_ramfs_mount passed");
        Ok(())
    })();

    // Cleanup on error.
    if region_attached {
        let _ = mm::mmio_free(RAMFS_MMIO_TAG);
    }
    if cap_acquired {
        let _ = pm::capctl(Capability::IoManagement, false);
    }

    result
}

