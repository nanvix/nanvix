/// Tests rename and unlink operations on the VFS.
fn test_rename_unlink() -> Result<(), Error> {
    ::syslog::info!("vfs-test: test_rename_unlink begin");

    vfs::create_mount("/ren", 128 * 1024).map_err(|e| fat_err(e, "create_mount /ren failed"))?;

    // Create a file.
    {
        let mut file: vfs::File = vfs::OpenOptions::new()
            .write(true)
            .create(true)
            .open("/ren/orig.txt")
            .map_err(|e| fat_err(e, "failed to create orig.txt"))?;
        file.write(b"rename me")
            .map_err(|e| fat_err(e, "failed to write orig.txt"))?;
        file.flush()
            .map_err(|e| fat_err(e, "failed to flush orig.txt"))?;
    }

    // Rename the file.
    vfs::rename("/ren/orig.txt", "/ren/moved.txt").map_err(|e| fat_err(e, "rename failed"))?;

    // Verify old name is gone.
    if vfs::stat("/ren/orig.txt").is_ok() {
        return Err(Error::new(
            ErrorCode::InvalidArgument,
            "orig.txt should not exist after rename",
        ));
    }

    // Verify new name exists with correct content.
    verify_file("/ren/moved.txt", b"rename me")?;

    // Unlink the renamed file.
    vfs::unlink("/ren/moved.txt").map_err(|e| fat_err(e, "unlink failed"))?;

    // Verify the file is gone.
    if vfs::stat("/ren/moved.txt").is_ok() {
        return Err(Error::new(
            ErrorCode::InvalidArgument,
            "moved.txt should not exist after unlink",
        ));
    }

    vfs::unmount("/ren").map_err(|e| fat_err(e, "unmount /ren failed"))?;

    ::syslog::info!("vfs-test: test_rename_unlink passed");
    Ok(())
}

//==================================================================================================
// Test: Chdir and Cwd
//==================================================================================================

/// Tests chdir and cwd operations on the VFS.
fn test_chdir_cwd() -> Result<(), Error> {
    ::syslog::info!("vfs-test: test_chdir_cwd begin");

    vfs::create_mount("/cd", 128 * 1024).map_err(|e| fat_err(e, "create_mount /cd failed"))?;

    // Create a subdirectory.
    vfs::mkdir("/cd/sub").map_err(|e| fat_err(e, "mkdir /cd/sub failed"))?;

    // Verify initial cwd is root.
    let initial_cwd: alloc::string::String = vfs::cwd().map_err(|e| fat_err(e, "cwd failed"))?;
    if initial_cwd != "/" {
        return Err(Error::new(ErrorCode::InvalidArgument, "initial cwd should be /"));
    }

    // Change to the mount root.
    vfs::chdir("/cd").map_err(|e| fat_err(e, "chdir /cd failed"))?;
    let cwd: alloc::string::String =
        vfs::cwd().map_err(|e| fat_err(e, "cwd after chdir failed"))?;
    if cwd != "/cd" {
        return Err(Error::new(ErrorCode::InvalidArgument, "cwd should be /cd"));
    }

    // Change to subdirectory.
    vfs::chdir("/cd/sub").map_err(|e| fat_err(e, "chdir /cd/sub failed"))?;
    let cwd2: alloc::string::String =
        vfs::cwd().map_err(|e| fat_err(e, "cwd after chdir sub failed"))?;
    if cwd2 != "/cd/sub" {
        return Err(Error::new(ErrorCode::InvalidArgument, "cwd should be /cd/sub"));
    }

    // Change back to root.
    vfs::chdir("/").map_err(|e| fat_err(e, "chdir / failed"))?;

    // Clean up.
    vfs::rmdir("/cd/sub").map_err(|e| fat_err(e, "rmdir /cd/sub failed"))?;
    vfs::unmount("/cd").map_err(|e| fat_err(e, "unmount /cd failed"))?;

    ::syslog::info!("vfs-test: test_chdir_cwd passed");
    Ok(())
}

