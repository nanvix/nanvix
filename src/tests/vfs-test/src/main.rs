/// Tests file truncation and sync on the VFS.
fn test_ftruncate_fsync() -> Result<(), Error> {
    ::syslog::info!("vfs-test: test_ftruncate_fsync begin");

    vfs::create_mount("/trunc", 128 * 1024)
        .map_err(|e| fat_err(e, "create_mount /trunc failed"))?;

    // Create a file with content.
    {
        let mut file: vfs::File = vfs::OpenOptions::new()
            .write(true)
            .create(true)
            .open("/trunc/file.txt")
            .map_err(|e| fat_err(e, "failed to create file.txt"))?;
        file.write(b"hello world!")
            .map_err(|e| fat_err(e, "failed to write file.txt"))?;
        file.flush()
            .map_err(|e| fat_err(e, "failed to flush file.txt"))?;
    }

    // Verify initial size.
    let info: vfs::Stat =
        vfs::stat("/trunc/file.txt").map_err(|e| fat_err(e, "stat file.txt failed"))?;
    if info.size() != 12 {
        return Err(Error::new(ErrorCode::InvalidArgument, "initial size should be 12"));
    }

    // Open and truncate to 5 bytes.
    {
        let mut file: vfs::File = vfs::OpenOptions::new()
            .read(true)
            .write(true)
            .open("/trunc/file.txt")
            .map_err(|e| fat_err(e, "failed to open file.txt for truncation"))?;
        file.seek(0, 5)
            .map_err(|e| fat_err(e, "seek to 5 failed"))?;
        file.truncate().map_err(|e| fat_err(e, "truncate failed"))?;
        file.flush()
            .map_err(|e| fat_err(e, "flush after truncate failed"))?;
    }

    // Verify truncated content.
    let info2: vfs::Stat =
        vfs::stat("/trunc/file.txt").map_err(|e| fat_err(e, "stat after truncate"))?;
    if info2.size() != 5 {
        return Err(Error::new(ErrorCode::InvalidArgument, "truncated size should be 5"));
    }
    verify_file("/trunc/file.txt", b"hello")?;

    // Clean up.
    vfs::unlink("/trunc/file.txt").map_err(|e| fat_err(e, "unlink file.txt"))?;
    vfs::unmount("/trunc").map_err(|e| fat_err(e, "unmount /trunc"))?;

    ::syslog::info!("vfs-test: test_ftruncate_fsync passed");
    Ok(())
}

