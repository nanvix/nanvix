/// Computes the absolute value of `n`.
///
/// If `n` is [`i64::MIN`], the result is [`i64::MIN`] due to two's complement wrapping.
#[cfg_attr(not(feature = "std"), unsafe(no_mangle))]
pub extern "C" fn imaxabs(n: intmax_t) -> intmax_t {
    n.wrapping_abs()
}

