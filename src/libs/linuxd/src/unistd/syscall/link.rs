use crate::{
    fcntl,
    unistd,
};

//==================================================================================================
// Standalone Functions
//==================================================================================================

pub fn link(odlpath: &str, newpath: &str) -> i32 {
    unistd::linkat(fcntl::AT_FDCWD, odlpath, fcntl::AT_FDCWD, newpath, 0)
}
