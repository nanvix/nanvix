#[inline(never)]
pub unsafe fn load_page_directory(cr3: usize) {
    arch::asm!(
        "mov {0}, %eax",
        "mov %eax, %cr3",
        "mov %cr0, %eax",
        "or $0x80000000, %eax",
        "mov %eax, %cr0",
        in(reg) cr3,
        options(nostack, att_syntax)
    );
}
