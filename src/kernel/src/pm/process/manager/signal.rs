///
/// # Description
///
/// Outcome of evaluating signal delivery at a return-to-user checkpoint.
///
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SignalDeliveryOutcome {
    /// No deliverable signal was pending; the thread resumes normally.
    None,
    /// A signal frame was built and the thread was redirected to its handler.
    Delivered,
    /// A frame could not be built safely; the caller must take the signal's default action and
    /// terminate the process.
    Escalate,
}

///
/// # Description
///
/// Outcome of evaluating a synchronous signal generated by a CPU exception on the faulting thread.
///
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SyncSignalOutcome {
    /// A signal frame was built; the caller must redirect the faulting context to `entry` with the
    /// stack pointer set to `frame_top`.
    Delivered {
        /// Address of the user-space signal handler to enter.
        entry: usize,
        /// Stack pointer the handler is entered with (top of the signal frame).
        frame_top: usize,
        /// Address of the registered user-space signal-return trampoline.
        restorer: usize,
        /// User address of the embedded `siginfo` image for an `SA_SIGINFO` handler (the handler's
        /// second argument), or `0` when the handler is not `SA_SIGINFO`. Consumed by the caller to
        /// populate the handler's argument register on register-argument ABIs (x86-64); ignored on
        /// stack-argument ABIs (x86), where it is already written to the frame.
        info_ptr: usize,
        /// User address of the embedded context image for an `SA_SIGINFO` handler (the handler's
        /// third argument), or `0` when the handler is not `SA_SIGINFO`. Consumed as for `info_ptr`.
        ctx_ptr: usize,
    },
    /// No catchable handler ran; the caller must take the signal's default action and terminate the
    /// process.
    Terminate,
}

///
/// # Description
///
/// Reason a `sigreturn()` request failed.
///
// `Unsupported` is returned only on architectures without a delivery path (whose trap-frame
// accessors are inert placeholders); `Forged` only where a real frame is built and then fails
// validation. The `sigreturn()` handler matches both.
#[allow(dead_code)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SigReturnFailure {
    /// The on-stack frame was corrupt or forged; the process must be terminated.
    Forged,
    /// `sigreturn()` is not implemented on this architecture.
    Unsupported,
}

