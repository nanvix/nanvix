use self::socket::Socket;
use ::syscall::{
    ffi::c_int,
    sys::socket::SocketAddr,
};

//==================================================================================================
// Modules
//==================================================================================================

pub mod fs;
pub mod socket;

//==================================================================================================
// RawFd
//==================================================================================================

type RawFd = c_int;

//==================================================================================================
// Error
//==================================================================================================

#[derive(Debug)]
pub struct Error {
    errno: c_int,
}

impl Error {
    pub fn value(&self) -> c_int {
        self.errno
    }
}

//==================================================================================================

pub fn setup_network(sockaddr: &SocketAddr) -> Result<Socket, Error> {
    let mut socket: Socket = socket::Socket::new()?;
    socket.bind(sockaddr)?;
    socket.listen(128)?;
    Ok(socket)
}
