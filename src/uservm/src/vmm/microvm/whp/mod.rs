/// IDT vector for IRQ 9 (IKC): PIC2 base (0x28) + (IRQ 9 - 8) = 0x29.
const IKC_VECTOR: u32 = 0x29;

/// Pvclock host timer period in microseconds (10 ms = 100 Hz). This timer
/// forces periodic VM exits via `WHvCancelRunVirtualProcessor` so the VMM loop
/// can update the pvclock `system_time` field. 100 Hz is high enough that the
/// guest sees sub-10 ms clock drift between LAPIC tick interpolations, yet low
/// enough to keep the VM-exit overhead negligible.
const PVCLOCK_TIMER_PERIOD_US: u64 = 10_000;

/// PIT oscillator frequency in Hz (1.193181 MHz).
const PIT_FREQ_HZ: u64 = 1_193_181;

//==================================================================================================
// PIT Channel 2 Emulation
//==================================================================================================

/// Minimal emulation of PIT channel 2 one-shot mode for LAPIC timer
/// calibration. Tracks channel 2 programming via port I/O and provides
/// the OUT2 status bit (bit 5 of port 0x61) based on elapsed host time.
///
/// This is the *only* PIT (8254) functionality emulated on WHP, and it
/// exists solely as a calibration fallback: the guest kernel programs PIT
/// channel 2 in one-shot mode and polls port 0x61 bit 5 to time a known
/// window when the host does not expose a TSC base frequency (CPUID leaf
/// 0x16 returns 0). When the TSC frequency *is* available the kernel
/// calibrates via RDTSC and never touches the PIT at all.
///
/// Full PIT emulation is deliberately omitted because timer *interrupts*
/// are never delivered through the PIT on WHP: the periodic scheduling
/// tick is generated by the WHP LAPIC emulator's own timer, and the
/// host-side [`timer::Timer`] only forces VM exits for pvclock updates.
/// Channel 0/1 programming and the other legacy PIT ports are therefore
/// handled as intentional no-ops in the PMIO dispatch loop.
struct PitCh2State {
    /// Whether channel 2 is in one-shot mode (mode 0).
    active: bool,
    /// Reload value for the countdown.
    reload: u16,
    /// Next byte expected: false = low byte, true = high byte.
    expect_hi: bool,
    /// Speaker gate enabled (bit 0 of port 0x61).
    gate_enabled: bool,
    /// Host timestamp when the countdown started.
    start_time: Option<Instant>,
}

impl PitCh2State {
    fn new() -> Self {
        Self {
            active: false,
            reload: 0,
            expect_hi: false,
            gate_enabled: false,
            start_time: None,
        }
    }

    /// Handles a write to port 0x43 (PIT control register).
    fn handle_ctrl_write(&mut self, byte: u8) {
        let channel: u8 = (byte >> 6) & 0x03;
        if channel != 2 {
            return;
        }
        // Mode 0 = interrupt on terminal count (one-shot).
        let mode: u8 = (byte >> 1) & 0x07;
        self.active = mode == 0;
        self.reload = 0;
        self.expect_hi = false;
        self.start_time = None;
    }

    /// Handles a write to port 0x42 (PIT channel 2 data register).
    fn handle_data_write(&mut self, byte: u8) {
        if !self.active {
            return;
        }
        if !self.expect_hi {
            self.reload = (self.reload & 0xFF00) | (byte as u16);
            self.expect_hi = true;
        } else {
            self.reload = (self.reload & 0x00FF) | ((byte as u16) << 8);
            self.expect_hi = false;
            if self.gate_enabled {
                self.start_time = Some(Instant::now());
            }
        }
    }

    /// Handles a write to port 0x61 (speaker/gate control).
    fn handle_speaker_write(&mut self, byte: u8) {
        self.gate_enabled = (byte & 0x01) != 0;
        if self.gate_enabled && self.active && self.reload > 0 && self.start_time.is_none() {
            self.start_time = Some(Instant::now());
        }
    }

    /// Reads port 0x61 (speaker status). Returns bit 5 (OUT2) set when
    /// the PIT channel 2 countdown has expired.
    fn read_speaker(&self) -> u8 {
        let mut result: u8 = if self.gate_enabled { 0x01 } else { 0x00 };
        if let Some(start) = self.start_time {
            let duration_ns: u64 = (self.reload as u64) * 1_000_000_000 / PIT_FREQ_HZ;
            if start.elapsed().as_nanos() as u64 >= duration_ns {
                result |= 0x20;
            }
        }
        result
    }
}

