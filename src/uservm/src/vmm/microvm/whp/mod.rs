#[derive(Clone)]
pub struct Vmm {
    /// Guest of the virtual machine.
    guest: Arc<Mutex<Guest>>,
    /// Virtual memory of the virtual machine.
    vmem: Arc<Mutex<VirtualMemory>>,
    /// Virtual processor of the virtual machine.
    vcpu: Arc<Mutex<VirtualProcessor>>,
    /// IKC notifier for waking the guest when credits are added.
    ikc_notifier: IkcNotifier,
    /// Partition handle, used to cancel the running vCPU (pvclock and
    /// guest-profiler timers). Also shared with [`IkcNotifier`] for interrupt
    /// delivery via the WHP LAPIC emulator. Not used for PIT emulation.
    partition_handle: windows::Win32::System::Hypervisor::WHV_PARTITION_HANDLE,
    /// Low-frequency host timer for pvclock updates. Calls
    /// `WHvCancelRunVirtualProcessor` at 100Hz while a vCPU run is pending to force VM exits so
    /// the VMM loop can update `system_time`. The LAPIC periodic timer
    /// handles actual 1kHz scheduling inside the WHP emulator (zero
    /// VM exits for timer delivery).
    timer: Arc<std::sync::Mutex<timer::Timer>>,
    /// Shared shutdown flag. When set to `true` from any thread, the VMM
    /// run loop will break on the next iteration.
    shutdown_flag: Arc<AtomicBool>,
    /// Synchronizes cancellation with entry to and return from `WHvRunVirtualProcessor`.
    run_state: Arc<RunState>,
    /// Wraps fields that don't require individual `Arc<Mutex<_>>`s.
    inner: Arc<Mutex<InteriorWhpHandle>>,
    /// Pvclock time base in nanoseconds. When restoring from a snapshot, this is set to
    /// the `system_time` value at snapshot time so that the guest sees monotonically
    /// increasing time (base + run-loop elapsed).
    pvclock_time_base_ns: Arc<std::sync::atomic::AtomicU64>,
    /// Last pvclock `system_time` value (nanoseconds) written to the guest. Used by
    /// `create_snapshot` to persist the current time without needing access to `loop_start`.
    pvclock_last_written_ns: Arc<std::sync::atomic::AtomicU64>,
    /// Performance timings collector for fine-grained startup breakdown.
    #[cfg(feature = "profile-time")]
    perf_timings: PerfTimings,
    /// Guest stack profiler (active when guest_profile_path is set).
    guest_profiler: Option<Arc<std::sync::Mutex<Vec<crate::guest_profiler::StackSample>>>>,
}

///
/// # Description
///
/// An internal structure to the VMM that wraps its contents in `Arc<Mutex<_>>`. It allows
/// the VMM to be clonable without wrapping each field in `Arc<Mutex<_>>`.
///
struct InteriorWhpHandle {
    /// WHP partition handle (must outlive vCPU and vmem).
    _partition: partition::WhpPartition,
    /// Emulator of the virtual machine.
    emulator: Emulator,
    /// Channel to receive commands from the VMM.
    control_rx: Receiver<VcpuControlCommand>,
    /// Channel to send control responses to the VMM.
    control_tx: Sender<VcpuControlResponse>,
    /// Kernel filename used for snapshot path derivation.
    kernel_filename: String,
    /// When true, the next guest-initiated snapshot request is silently skipped.
    skip_next_snapshot: bool,
    /// When true, the guest is entitled to take exactly one snapshot.
    /// Set from the `snapshot` kernel option; consumed on the first successful request.
    snapshot_allowed: bool,
}

/// Synchronizes cancellation with `WHvRunVirtualProcessor`.
struct RunState {
    /// Whether the vCPU is about to enter or is blocked in `WHvRunVirtualProcessor`.
    pending: AtomicBool,
    /// Serializes cancellation calls with transitions out of the pending state.
    cancel_gate: std::sync::Mutex<()>,
}

impl RunState {
    fn new() -> Self {
        Self {
            pending: AtomicBool::new(false),
            cancel_gate: std::sync::Mutex::new(()),
        }
    }

    fn lock_cancel_gate(&self) -> std::sync::MutexGuard<'_, ()> {
        match self.cancel_gate.lock() {
            Ok(guard) => guard,
            Err(poisoned) => poisoned.into_inner(),
        }
    }

    fn begin_run(&self) {
        let _guard: std::sync::MutexGuard<'_, ()> = self.lock_cancel_gate();
        self.pending.store(true, Ordering::SeqCst);
    }

    fn finish_run(&self) {
        let _guard: std::sync::MutexGuard<'_, ()> = self.lock_cancel_gate();
        self.pending.store(false, Ordering::SeqCst);
    }

    fn is_pending(&self) -> bool {
        self.pending.load(Ordering::SeqCst)
    }

    /// Runs `cancel` only while a vCPU entry is pending. Holding `cancel_gate` until the call
    /// returns ensures that once [`RunPendingGuard`] is dropped, no cancellation can overlap with
    /// snapshot or teardown operations on the same WHP partition.
    fn cancel_if_pending<F>(&self, cancel: F) -> bool
    where
        F: FnOnce(),
    {
        let _guard: std::sync::MutexGuard<'_, ()> = self.lock_cancel_gate();
        if self.pending.load(Ordering::SeqCst) {
            cancel();
            true
        } else {
            false
        }
    }
}

/// Clears the WHP run-pending state whenever a vCPU entry attempt finishes or unwinds.
struct RunPendingGuard<'a> {
    run_state: &'a RunState,
}

impl<'a> RunPendingGuard<'a> {
    fn new(run_state: &'a RunState) -> Self {
        run_state.begin_run();
        Self { run_state }
    }
}

impl Drop for RunPendingGuard<'_> {
    fn drop(&mut self) {
        self.run_state.finish_run();
    }
}

/// Repeatedly requests cancellation until the pending or active WHP run finishes.
fn cancel_while_run_pending<F>(run_state: &RunState, mut cancel: F)
where
    F: FnMut(),
{
    while run_state.cancel_if_pending(&mut cancel) {
        std::thread::sleep(std::time::Duration::from_millis(1));
    }
}

